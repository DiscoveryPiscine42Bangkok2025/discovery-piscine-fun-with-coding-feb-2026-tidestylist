# ตรวจสอบว่าจำนวนอาร์กิวเมนต์ ($#) เท่ากับ 0 หรือไม่
if [ $# -eq 0 ]; then
    echo "No arguments supplied"
else
    # ถ้ามีค่า ให้แสดงตัวที่ 1
    echo "$1"
    # ถ้ามีมากกว่าหรือเท่ากับ 2 ตัว ให้แสดงตัวที่ 2
    if [ $# -ge 2 ]; then
        echo "$2"
    fi
    # ถ้ามีมากกว่าหรือเท่ากับ 3 ตัว ให้แสดงตัวที่ 3
    if [ $# -ge 3 ]; then
        echo "$3"
    fi
fi